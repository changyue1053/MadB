FEATURE = "core.external-runtime-verification@1"


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value))


def reference(root, name, schema=None):
    data = (root / name).read_bytes()
    result = {"path": name, "sha256": "sha256:" + hashlib.sha256(data).hexdigest(), "size": len(data)}
    if schema:
        result["schema"] = schema
    return result


class PackagePrepared(Exception):
    pass


class FixturePipeline(FrozenPipeline):
    driver = worker = "worker.py"
    packer = "packer.py"

    def common_inputs(self, metadata=False):
        return [reference(self.root, "worker.py"), reference(self.root, "backend.json")]

    def public_generated(self):
        return []

    def public_built(self):
        return ["artifact.bin"]

    def execute(self, command, bundle, *extra):
        # Simulate only the host's committed records. The preparation helper is
        # real Python code with import/run markers; these are no host acceptance tests.
        self.executions.append((command, bundle))
        if bundle["operation"] == "generate":
            batch = self.root / "domain/batches" / ("a" * 64)
            files = batch / "files"
            files.mkdir(parents=True)
            (files / "generated.txt").write_bytes(b"committed generated bytes")
            output = {"schema": "madb.output-set/1", "generation_id": "sha256:" + "b" * 64,
                      "input_digest": self.contract["source_digest"], "task_digest": "sha256:" + "c" * 64,
                      "profile_digest": self.read["selector"]["profile_digest"], "files": [reference(files, "generated.txt")], "manifest_path": "outputs.json"}
            write(files / "outputs.json", output)
            metadata = {"schema": "madb.storage-batch/1", "id": "sha256:" + "a" * 64,
                        "spec": {"layer": "source", "profile_digest": output["profile_digest"],
                                 "input_digest": output["input_digest"], "task_digest": output["task_digest"],
                                 "generation_id": output["generation_id"]},
                        "files": [reference(files, "outputs.json"), reference(files, "generated.txt")]}
            write(batch / "metadata.json", metadata)
            write(self.root / "domain/current.json", {"source": metadata["id"]})
        elif bundle["operation"] == "build":
            current = json.loads((self.root / "domain/current.json").read_text())
            current["build"] = "sha256:" + "d" * 64
            write(self.root / "domain/current.json", current)
        elif bundle["operation"] == "package":
            raise PackagePrepared()
        else:
            raise AssertionError("unexpected fixture operation")
        return ""


class PipelineTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="madb-c07-pipeline-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)

    def subject(self, *, required=False, supported=False, phases=None, generated=True):
        profile = json.loads((ROOT / "tests/fixtures/contracts/profile.json").read_text())
        if required:
            profile["required_features"].append(FEATURE)
        if supported:
            profile["supported_features"].append(FEATURE)
        write(self.root / "profile.json", profile)
        selector = {"route": profile["route"], "profile_id": profile["id"], "profile_digest": profile_digest(profile),
                    "target": profile["target"], "direction": profile["direction"]}
        contract = {"selector": selector, "source_digest": "sha256:" + "1" * 64,
                    "structure_digest": "sha256:" + "2" * 64, "policy_digest": "sha256:" + "3" * 64, "symbols": []}
        write(self.root / "contract.json", contract)
        for name in ("project.json", "madb.lock", "backend.json"):
            write(self.root / name, {})
        read = {"schema": "madb.read-request/1", "selector": selector, "inputs": [],
                "profile": reference(self.root, "profile.json", "madb.profile/1")}
        write(self.root / "read.json", read)
        marker = self.root / "helper-events.txt"
        (self.root / "worker.py").write_text(
            "from pathlib import Path\n"
            + "marker = Path(" + repr(str(marker)) + ")\n"
            + "with marker.open('a') as stream: stream.write('import\\n')\n"
            + "def run_phase(config, phase, inputs, work):\n"
            + "    previous = {'link': 'compile.bin', 'run': 'link.bin'}.get(phase)\n"
            + "    if previous: assert (inputs / previous).read_text() == previous[:-4]\n"
            + "    with marker.open('a') as stream: stream.write(phase + '\\n')\n"
            + "    (work / (phase + '.bin')).write_text(phase)\n"
            + "    return [phase + '.bin']\n")
        host = self.root / "host"
        host.write_bytes(b"fixture image; never launched")
        python = Path(sys.executable).resolve()
        prepared = {"read": read, "lock": {}, "config": {"tools": {"python": {
            "id": "python", "version": "fixture", "path": str(python),
            "sha256": reference(python.parent, python.name)["sha256"], "size": python.stat().st_size}}}}
        subject = FixturePipeline(ROOT, self.root, prepared, host)
        subject.executions = []
        subject.contract = contract
        if phases is not None:
            subject.build_phases = lambda: phases
        if generated:
            subject.generate()
        return subject

    def assert_no_preparation(self, subject, message):
        with self.assertRaisesRegex(ValueError, message):
            subject.build()
        self.assertFalse((self.root / "helper-events.txt").exists())
        self.assertFalse((self.root / "prepare").exists())
        self.assertFalse(any(bundle["operation"] == "build" for _, bundle in subject.executions))

    def test_default_chain_runs_real_helper_in_previous_output_order(self):
        subject = self.subject()
        self.assertEqual(subject.build_phases(), ("compile", "link", "run"))
        subject.build()
        self.assertEqual((self.root / "helper-events.txt").read_text().splitlines(), ["import", "compile", "link", "run"])
        tasks = [json.loads((self.root / "tasks" / (phase + ".json")).read_text()) for phase in ("compile", "link", "run")]
        self.assertEqual([task["dependencies"] for task in tasks], [[], ["compile"], ["link"]])
        self.assertIn("compile.bin", [item["path"] for item in tasks[1]["inputs"]])
        self.assertIn("link.bin", [item["path"] for item in tasks[2]["inputs"]])

    def test_explicit_external_mode_prepares_two_phases(self):
        subject = self.subject(required=True, supported=True, phases=("compile", "link"))
        subject.build()
        self.assertEqual((self.root / "helper-events.txt").read_text().splitlines(), ["import", "compile", "link"])
        self.assertFalse((self.root / "tasks/run.json").exists())
        self.assertEqual(len(subject.executions[-1][1]["tasks"]), 2)

    def test_supported_only_keeps_default_three_phases(self):
        subject = self.subject(supported=True)
        subject.build()
        self.assertEqual((self.root / "helper-events.txt").read_text().splitlines(), ["import", "compile", "link", "run"])

    def test_supported_only_cannot_select_two_phases(self):
        self.assert_no_preparation(self.subject(supported=True, phases=("compile", "link")), "phase plan")

    def test_external_run_is_rejected_before_even_importing_helper(self):
        self.assert_no_preparation(self.subject(required=True, supported=True), "phase plan")

    def test_whole_invalid_plan_is_rejected_before_any_phase(self):
        subject = self.subject(required=True, supported=True)
        for plan in ((), ("compile",), ("link", "compile"), ("compile", "link", "link"),
                     ("compile", "link", "metadata"), ("compile", "link", "run")):
            with self.subTest(plan=plan):
                subject.build_phases = lambda: iter(plan)
                self.assert_no_preparation(subject, "phase plan")

    def test_missing_host_generation_is_rejected(self):
        self.assert_no_preparation(self.subject(generated=False), "successful host generation")

    def test_required_but_unsupported_mode_is_rejected(self):
        # A real host rejects this profile during metadata. Even the narrow
        # adapter guard must not prepare it if a test supplies such a context.
        self.assert_no_preparation(self.subject(required=True, phases=("compile", "link")), "not supported")

    def test_replaced_profile_or_reference_cannot_switch_policy(self):
        subject = self.subject()
        profile = json.loads((self.root / "profile.json").read_text())
        profile["required_features"].append(FEATURE)
        profile["supported_features"].append(FEATURE)
        write(self.root / "profile.json", profile)
        subject.build_phases = lambda: ("compile", "link")
        self.assert_no_preparation(subject, "profile differs")
        subject.read["profile"] = reference(self.root, "profile.json", "madb.profile/1")
        self.assert_no_preparation(subject, "profile differs")
        subject.read["selector"]["profile_digest"] = profile_digest(profile)
        self.assert_no_preparation(subject, "context differs")

    def test_mutated_contract_and_generation_state_are_rejected(self):
        subject = self.subject()
        original = deepcopy(subject.outputs)
        subject.outputs["generation_id"] = "sha256:" + "f" * 64
        self.assert_no_preparation(subject, "generation identity changed")
        subject.outputs = original
        subject.contract["source_digest"] = "sha256:" + "f" * 64
        self.assert_no_preparation(subject, "contract differs")

    def test_replaced_committed_metadata_or_current_source_is_rejected(self):
        subject = self.subject()
        metadata = subject.source.parent / "metadata.json"
        original = metadata.read_text()
        value = json.loads(original)
        value["spec"]["profile_digest"] = "sha256:" + "f" * 64
        write(metadata, value)
        self.assert_no_preparation(subject, "generation identity changed")
        metadata.write_text(original)
        write(self.root / "domain/current.json", {"source": "sha256:" + "f" * 64})
        self.assert_no_preparation(subject, "context differs")

    def test_initial_mismatched_source_lineage_is_rejected(self):
        subject = self.subject()
        # Represent a bad host fixture result before its snapshot was recorded;
        # matching file hashes alone must not erase the lineage mismatch.
        metadata = subject.source.parent / "metadata.json"
        value = json.loads(metadata.read_text())
        value["spec"]["generation_id"] = "sha256:" + "f" * 64
        write(metadata, value)
        subject._generated_context["metadata_digest"] = reference(metadata.parent, metadata.name)["sha256"]
        self.assert_no_preparation(subject, "lineage does not match")

    def test_changed_worker_is_rejected_before_import_with_original_or_recomputed_refs(self):
        subject = self.subject()
        worker = self.root / "worker.py"
        worker.write_text(worker.read_text() + "\n# modified after generation\n")
        self.assert_no_preparation(subject, "preparation inputs differ")
        subject.common_inputs = lambda: deepcopy(subject._generated_context["preparation_inputs"])
        self.assert_no_preparation(subject, "frozen input changed: worker.py")

    def test_changed_generated_bytes_are_rejected_before_import(self):
        subject = self.subject()
        original_refs = deepcopy(subject.outputs["files"])
        (subject.source / "generated.txt").write_bytes(b"uncommitted replacement")
        self.assert_no_preparation(subject, "frozen input changed: generated.txt")
        self.assertEqual(subject.outputs["files"], original_refs)

    def test_replaced_host_is_rejected_before_preparation(self):
        subject = self.subject()
        subject.binary.write_bytes(b"changed host")
        with self.assertRaisesRegex(RuntimeError, "locked MadB host image changed"):
            subject.build()
        self.assertFalse((self.root / "helper-events.txt").exists())
        self.assertFalse((self.root / "prepare").exists())

    def test_worker_missing_from_checked_inputs_is_rejected_before_import(self):
        subject = self.subject(generated=False)
        subject.common_inputs = lambda metadata=False: [reference(self.root, "backend.json")]
        subject.generate()
        self.assert_no_preparation(subject, "worker is not a host-checked input")

    def test_package_uses_complete_committed_references_not_stray_files(self):
        subject = self.subject()
        subject.built = self.root / "domain/batches" / ("d" * 64) / "files"
        evidence = []
        for index in range(4):
            name = f"evidence/task-{index:04}.json"
            write(subject.built / name, {"fixture": index})
            evidence.append(reference(subject.built, name))
        (subject.built / "artifact.bin").write_bytes(b"built artifact")
        files = [reference(subject.built, "artifact.bin"), *reversed(evidence)]
        write(subject.built.parent / "metadata.json", {"files": files})
        write(subject.built / "evidence/task-9999.json", {"uncommitted": True})
        write(self.root / "toolchain.json", {})
        with self.assertRaises(PackagePrepared):
            subject.package(self.root / "candidate", "revision", ["target-required-case"])
        request = json.loads((self.root / "package-request.json").read_text())
        expected = [dict(item, schema="madb.build-evidence/1") for item in evidence]
        self.assertEqual(request["build_evidence"], expected)
        self.assertEqual(request["required_cases"], ["target-required-case"])
        package_inputs = subject.executions[-1][1]["recipe"]["inputs"]
        self.assertNotIn("evidence/task-9999.json", [item["path"] for item in package_inputs])


class EvidenceInventoryTests(unittest.TestCase):
    def metadata(self, names):
        return {"files": [{"path": name, "sha256": "sha256:" + str(index % 10) * 64, "size": index + 1}
                          for index, name in enumerate(names)]}

    def test_two_three_and_many_references_preserve_original_hash_and_size(self):
        for count in (2, 3, 5):
            with self.subTest(count=count):
                metadata = self.metadata([f"evidence/task-{i:04}.json" for i in range(count)])
                expected = [dict(item, schema="madb.build-evidence/1") for item in metadata["files"]]
                metadata["files"].reverse()
                self.assertEqual(committed_build_evidence(metadata), expected)

    def test_empty_duplicate_gapped_and_malformed_evidence_fail(self):
        invalid = [[], ["artifact.bin"], ["evidence/task-0000.json"] * 2,
                   ["evidence/task-0001.json"], ["evidence/task-0000.json", "evidence/task-0002.json"]]
        invalid += [[name] for name in ("evidence/task-0.json", "evidence/task-00000.json", "evidence/task-000x.json",
                                       "evidence/task--001.json", "evidence/task-００００.json", "evidence/task-0000.json/extra")]
        for names in invalid:
            with self.subTest(names=names), self.assertRaises(ValueError):
                committed_build_evidence(self.metadata(names))

    def test_missing_or_invalid_reference_identity_fails(self):
        for field, value in (("sha256", "sha256:wrong"), ("size", -1), ("size", True), ("size", None)):
            metadata = self.metadata(["evidence/task-0000.json"])
            metadata["files"][0][field] = value
            with self.subTest(field=field, value=value), self.assertRaisesRegex(ValueError, "invalid committed evidence reference"):
                committed_build_evidence(metadata)


