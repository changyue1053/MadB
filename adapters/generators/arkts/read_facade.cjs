'use strict';
// AST-only compiler helper. C04 driver verifies original source/tool references
// before and after invoking this file; stdin is the already-verified source.
const fs = require('node:fs');
const crypto = require('node:crypto');
const {TextDecoder} = require('node:util');
function readFacade(ts, bytes, logical, mode = 'source') {
  const testProfile=mode.endsWith('-test');
  if(testProfile) mode=mode.slice(0,-5);
  if (!['source','declaration'].includes(mode)) throw new Error('unknown public reader mode');
  if (bytes.length > 1024 * 1024) throw new Error('facade source exceeds 1 MiB');
  const text = new TextDecoder('utf-8', {fatal:true}).decode(bytes);
  const sf = ts.createSourceFile(logical, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  function loc(n) {
    const start=n.getStart(sf),end=n.getEnd(),a=sf.getLineAndCharacterOfPosition(start),b=sf.getLineAndCharacterOfPosition(end);
    return {path:logical,line:a.line+1,column:a.character+1,endLine:b.line+1,endColumn:b.character+1,start,end,offsets:'utf16'};
  }
  function fail(n,message) {const p=loc(n);throw new Error(`${logical}:${p.line}:${p.column}: ${message}`);}
  function id(n) {if(!n||!ts.isIdentifier(n)||!/^[A-Za-z_][A-Za-z0-9_]*$/.test(n.text))fail(n||sf,'plain identifier required');return n.text;}
  function modifiers(n, expected) {const values=Array.from(n.modifiers||[],x=>x.kind);if(JSON.stringify(values)!==JSON.stringify(expected))fail(n,'ARKTS_DECL_UNSUPPORTED_MODIFIERS: unsupported export/member modifiers');}
  if(sf.parseDiagnostics.length){const d=sf.parseDiagnostics[0],p=sf.getLineAndCharacterOfPosition(d.start||0);throw new Error(`${logical}:${p.line+1}:${p.character+1}: ${ts.flattenDiagnosticMessageText(d.messageText,' ')}`);}
  if(sf.referencedFiles.length||sf.typeReferenceDirectives.length||sf.libReferenceDirectives.length)fail(sf,'reference directives unsupported');
  function unique(items,n){const names=items.map(x=>x.name);if(new Set(names).size!==names.length)fail(n,'duplicate declaration/member');}
  function type(n, depth=0) {
    if(!n||depth>8)fail(n||sf,'missing/deep type');
    if(n.kind===ts.SyntaxKind.NumberKeyword)return {tag:'number'};
    if(n.kind===ts.SyntaxKind.StringKeyword)return {tag:'string'};
    if(n.kind===ts.SyntaxKind.VoidKeyword)return {tag:'void'};
    if(testProfile&&ts.isArrayTypeNode(n)&&n.elementType.kind===ts.SyntaxKind.NumberKeyword)return {tag:'array',item:{tag:'number'}};
    if(ts.isTypeReferenceNode(n)){
      const name=id(n.typeName);
      if(name==='Promise'&&n.typeArguments?.length===1){const item=type(n.typeArguments[0],depth+1);if(!['void','reference'].includes(item.tag))fail(n,'Promise result unsupported');return {tag:'promise',item};}
      if(!n.typeArguments?.length)return {tag:'reference',name};
    }
    if(ts.isFunctionTypeNode(n)){
      if(n.typeParameters?.length)fail(n,'generic callback unsupported');
      const returns=type(n.type,depth+1);if(returns.tag!=='void')fail(returns.tag==='promise'?n.type:n,'ARKTS_DECL_CALLBACK_RESULT: callback must return void');
      return {tag:'callback',params:params(n,depth+1),returns};
    }
    fail(n,'unsupported public type: '+ts.SyntaxKind[n.kind]);
  }
  function params(n,depth=0) {
    if(n.typeParameters?.length||n.parameters.length>8)fail(n,'generic/oversized callable');
    const values=Array.from(n.parameters,p=>{
      modifiers(p,[]);if(p.questionToken||p.dotDotDotToken||p.initializer)fail(p,'optional/rest/default parameter unsupported');
      const name=id(p.name),t=type(p.type,depth+1);
      if(name==='this'||['void','promise'].includes(t.tag))fail(p,'this/void/Promise parameter unsupported');
      return {name,type:t,location:loc(p)};
    });unique(values,n);return values;
  }
  function callable(n, owner) {
    if(n.questionToken||n.asteriskToken)fail(n,'optional/generator method unsupported');
    return {name:id(n.name),owner,params:params(n),returns:type(n.type),location:loc(n)};
  }
  const records=[],resources=[],errors=[],functions=[],imports=[];
  for(const n of sf.statements){
    if(ts.isImportDeclaration(n)){
      if(!ts.isStringLiteral(n.moduleSpecifier))fail(n,'import module must be literal');
      imports.push({module:n.moduleSpecifier.text,location:loc(n)});continue;
    }
    const exported=Array.from(n.modifiers||[]).some(m=>m.kind===ts.SyntaxKind.ExportKeyword);
    if(!exported){
      // Implementations are authored, not inferred or re-generated by this reader.
      // Export assignments/declarations have no Export modifier and must still reject.
      if(ts.isExportDeclaration(n)||ts.isExportAssignment(n))fail(n,'re-export/default export unsupported');
      continue;
    }
    modifiers(n,mode==='declaration'&&(ts.isClassDeclaration(n)||ts.isFunctionDeclaration(n))?[ts.SyntaxKind.ExportKeyword,ts.SyntaxKind.DeclareKeyword]:[ts.SyntaxKind.ExportKeyword]);
    if(ts.isInterfaceDeclaration(n)){
      if(n.typeParameters?.length||n.heritageClauses?.length||!n.members.length||n.members.length>64)fail(n,'generic/inherited/empty/oversized interface');
      const name=id(n.name),fields=[],methods=[];
      for(const m of n.members){
        modifiers(m,[]);
        if(ts.isPropertySignature(m)){
          if(m.questionToken||m.initializer)fail(m,'record property must be required');
          const t=type(m.type);if(!['number','string'].includes(t.tag))fail(m,'record fields must be scalar');
          fields.push({name:id(m.name),type:t,location:loc(m)});
        }else if(ts.isMethodSignature(m))methods.push(callable(m,name));
        else fail(m,'unsupported interface member');
      }
      unique([...fields,...methods],n);
      if(fields.length&&methods.length)fail(n,'mixed record/resource interface unsupported');
      if(fields.length)records.push({name,fields,location:loc(n)});
      else resources.push({name,methods,location:loc(n)});
    }else if(ts.isClassDeclaration(n)){
      if(n.typeParameters?.length)fail(n,'generic error class unsupported');
      const heritage=Array.from(n.heritageClauses||[]);
      if(heritage.length!==2||heritage[0].token!==ts.SyntaxKind.ExtendsKeyword||heritage[1].token!==ts.SyntaxKind.ImplementsKeyword
         ||heritage.some(h=>h.types.length!==1||!ts.isIdentifier(h.types[0].expression)||h.types[0].expression.text!=='Error'||h.types[0].typeArguments?.length))fail(n,'only an explicit Error subclass is supported');
      const fields=[],constructors=[];
      for(const m of n.members){
        if(ts.isPropertyDeclaration(m)){
          modifiers(m,[ts.SyntaxKind.ReadonlyKeyword]);
          if(m.questionToken||m.exclamationToken||m.initializer)fail(m,'error field must be a readonly declared property');
          fields.push({name:id(m.name),type:type(m.type),location:loc(m)});
        }else if(ts.isConstructorDeclaration(m)){
          modifiers(m,[]);if((mode==='source')!==Boolean(m.body))fail(m,'constructor body disagrees with source/declaration mode');
          constructors.push({params:params(m),location:loc(m)});
        }else fail(m,'unsupported exported Error member');
      }
      unique(fields,n);
      if(fields.length!==1||fields[0].type.tag!=='string'||constructors.length!==1)fail(n,'expected one string error property and constructor');
      errors.push({name:id(n.name),fields,constructors,location:loc(n)});
    }else if(ts.isFunctionDeclaration(n)){
      if((mode==='source')!==Boolean(n.body))fail(n,'function body disagrees with source/declaration mode');
      functions.push(callable(n,null));
    }else fail(n,'unsupported exported declaration: '+ts.SyntaxKind[n.kind]);
  }
  unique([...records,...resources,...errors,...functions],sf);
  if(!records.length||!resources.length||errors.length!==1||!functions.length||records.length+resources.length+functions.length>64)fail(sf,'public declaration counts outside restricted profile');
  const types=new Map([...records.map(r=>[r.name,'record']),...resources.map(r=>[r.name,'resource'])]);
  function check(t,location,where){
    const bad=message=>{throw new Error(`${logical}:${location.line}:${location.column}: ${message}`);};
    if(t.tag==='reference'&&!types.has(t.name))bad('unknown public type reference '+t.name);
    if(t.tag==='promise'){if(where!=='return')bad('Promise only supported as callable return');check(t.item,location,'result');}
    if(t.tag==='callback'){
      if(where!=='parameter')bad('callback only supported as callable parameter');
      for(const p of t.params){if(p.type.tag!=='reference'||types.get(p.type.name)!=='record')bad('callback parameters must be declared records');}
    }
  }
  for(const f of [...functions,...resources.flatMap(r=>r.methods)]){
    for(const p of f.params)check(p.type,p.location,'parameter');check(f.returns,f.location,'return');
  }
  return {schema:'madb.private.arkts-public-declarations.v1',authority:mode==='source'?'exported-arkts-declarations':'compiled-arkts-declarations',
    source:{path:logical,sha256:'sha256:'+crypto.createHash('sha256').update(bytes).digest('hex'),size:bytes.length},
    compilerApiVersion:ts.version,records,resources,errors,functions,imports};
}
if(require.main===module){
  try{
    if(process.argv.length!==4&&process.argv.length!==5)throw new Error('expected locked TypeScript module path, logical source name, optional source/declaration mode');
    const ts=require(process.argv[2]);const data=fs.readFileSync(0);
    process.stdout.write(JSON.stringify(readFacade(ts,data,process.argv[3],process.argv[4]||'source'),null,2)+'\n');
  }catch(e){process.stderr.write(String(e.message||e)+'\n');process.exitCode=1;}
}
module.exports={readFacade};
