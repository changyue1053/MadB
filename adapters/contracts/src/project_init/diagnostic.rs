pub(super) fn registered_code(code: Id) -> Result<Id> {
    if REGISTERED.binary_search(&code.as_str()).is_err() {
        return Err(invalid(
            "diagnostic.code",
            "diagnostic code is not registered by this producer",
        ));
    }
    Ok(code)
}
